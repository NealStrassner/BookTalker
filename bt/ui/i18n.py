def system_language():
    """The Windows display language, if BookTalker speaks it, else English."""
    try:
        import ctypes
        lcid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        code = (locale.windows_locale.get(lcid) or "en")[:2]
    except Exception:
        code = (locale.getlocale()[0] or "en")[:2]
    return code if code in UI_LANGS else "en"


