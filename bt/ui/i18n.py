def lang_label(code, lower=False):
    """A language's name in the interface language (the 8 main ones), else in itself."""
    name = NAMES[_lang].get(code) or AUTONYM.get(code) or code.upper()
    return name.lower() if lower and _lang in LOWER_IN_SENTENCES and code in NAMES[_lang] else name


def lang_values(code):
    """Format values for templates that mention a language mid-sentence or at the start."""
    return {"lang": lang_label(code), "lang_l": lang_label(code, lower=True)}
